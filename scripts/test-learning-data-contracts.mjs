import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import {runInNewContext} from 'node:vm';
const require=createRequire(import.meta.url);
const ts=require('typescript');
const source=readFileSync('app/learn/data-contracts.ts','utf8');
const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const exports={};
runInNewContext(js,{exports,Date,JSON,Number,Object,RegExp});
const {validateLearnerNoteInput:note,validateLearningEventInput:event}=exports;
const goodNote={resourceRef:'linux/intro',content:'Test note',expectedVersion:1};
assert.equal(note(goodNote).ok,true,'valid note');
assert.equal(note({...goodNote,userId:'attacker'}).ok,false,'client owner ID rejected');
assert.equal(note({...goodNote,resourceRef:'../secret'}).ok,false,'traversal rejected');
assert.equal(note({...goodNote,resourceRef:'linux//intro'}).ok,false,'double slash rejected');
assert.equal(note({...goodNote,content:'x'.repeat(20001)}).ok,false,'oversize note rejected');
assert.equal(note({...goodNote,expectedVersion:0}).ok,false,'invalid version rejected');
assert.equal(note(null).ok,false,'null rejected');
const goodEvent={resourceRef:'linux/intro',eventType:'recall_submitted',idempotencyKey:'event_123456',occurredAt:'2026-11-09T07:00:00Z',payload:{score:3}};
assert.equal(event(goodEvent).ok,true,'valid event');
assert.equal(event({...goodEvent,userId:'attacker'}).ok,false,'event owner rejected');
assert.equal(event({...goodEvent,eventType:'grant_credential'}).ok,false,'unapproved event rejected');
assert.equal(event({...goodEvent,idempotencyKey:'bad!'}).ok,false,'invalid idempotency key rejected');
assert.equal(event({...goodEvent,payload:{text:'x'.repeat(5000)}}).ok,false,'oversize payload rejected');
assert.equal(event({...goodEvent,occurredAt:'not-a-date'}).ok,false,'invalid date rejected');
assert.equal(event({...goodEvent,payload:[]}).ok,false,'array payload rejected');
console.log('PASS: executable learner note and event input validation cases.');
